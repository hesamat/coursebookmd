/**
 * Generate the Python builtin docs dataset used by hover previews.
 *
 * The dataset is not committed: this script downloads the official functions
 * page once (cached under node_modules/.cache), extracts every documented
 * function and class with a callable signature, and writes
 * generated/python-builtins.js. Dev, build,
 * test, and export entry points call ensurePythonDocs() before importing the
 * renderer, so a fresh checkout only needs network access on its first run.
 *
 * CLI:
 *   node tools/generate-python-docs.mjs [--refresh]
 */
import fs from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { fileURLToPath, pathToFileURL } from "node:url";
import { JSDOM } from "jsdom";

const PROJECT_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

export const PYTHON_DOCS_VERSION = "3.14";
export const PYTHON_DOCS_SOURCE_URL = `https://docs.python.org/${PYTHON_DOCS_VERSION}/builtins/functions.html`;
// Link to the exact docs version the cards were generated from, so a hovered
// signature and the page it opens cannot drift apart.
export const PYTHON_DOCS_URL = PYTHON_DOCS_SOURCE_URL;

const CACHE_PATH = path.join(
  PROJECT_ROOT,
  "node_modules",
  ".cache",
  "coursebookmd",
  "python-docs",
  `${PYTHON_DOCS_VERSION}-builtins-functions.html`,
);
const OUTPUT_PATH = path.join(PROJECT_ROOT, "generated", "python-builtins.js");
const MIN_HTML_BYTES = 100_000;
const MIN_ENTRIES = 50;
const REQUIRED_NAMES = ["len", "print", "sorted", "zip"];

function normalizeSignature(text) {
  return text
    .replace(/¶\s*$/, "")
    .replace(/\s+/g, " ")
    .trim()
    .replace(/^awaitable\s+/, "")
    .replace(/^class\s+/, "");
}

function normalizeText(text) {
  return text.replace(/\s+/g, " ").trim();
}

/**
 * Parse the functions page into the dataset shape. Exported separately so
 * tests can exercise the HTML mapping without touching the network.
 *
 * @param {string} html
 * @returns {Record<string, { anchor: string, signatures: string[], summary: string }>}
 */
export function parsePythonDocsHtml(html) {
  const document = new JSDOM(html).window.document;
  const entries = {};

  for (const dl of document.querySelectorAll("dl.py.function, dl.py.class")) {
    const definitions = [...dl.querySelectorAll(":scope > dt")];
    const first = definitions[0];
    if (!first) continue;

    // property.getter and friends document an attribute of a class; their
    // visible name drops the class prefix, so they must not become builtins.
    if (first.querySelector(".sig-prename")) continue;

    const name = normalizeText(first.querySelector(".sig-name")?.textContent ?? "");
    if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(name)) continue;

    // Functions put the anchor on the signature; classes put it on the
    // wrapper (dict -> func-dict, range -> func-range). Sphinx also emits
    // index-* ids on wrappers, which are not stable documentation anchors.
    const annotationAnchor = first.id;
    const wrapperAnchor = dl.id;
    const anchor =
      annotationAnchor && !annotationAnchor.startsWith("index-")
        ? annotationAnchor
        : wrapperAnchor;
    if (!anchor || anchor.startsWith("index-")) continue;

    const signatures = definitions
      .map((definition) => normalizeSignature(definition.textContent))
      .filter((signature) => signature.startsWith(`${name}(`));
    if (signatures.length === 0) continue;

    const summary = normalizeText(dl.querySelector(":scope > dd > p")?.textContent ?? "");
    if (!summary) continue;

    if (!entries[name]) entries[name] = { anchor, signatures, summary };
  }

  return entries;
}

async function readCachedHtml() {
  try {
    const html = await fs.readFile(CACHE_PATH, "utf8");
    return html.length >= MIN_HTML_BYTES ? html : null;
  } catch {
    return null;
  }
}

async function fetchHtml() {
  const response = await fetch(PYTHON_DOCS_SOURCE_URL, {
    headers: { accept: "text/html" },
    signal: AbortSignal.timeout(30000),
  });
  if (!response.ok) {
    throw new Error(
      `Could not download ${PYTHON_DOCS_SOURCE_URL}: HTTP ${response.status}`,
    );
  }
  const html = await response.text();
  if (html.length < MIN_HTML_BYTES) {
    throw new Error(
      `Downloaded ${PYTHON_DOCS_SOURCE_URL}, but the page was only ${html.length} bytes.`,
    );
  }
  return html;
}

function renderModule(entries) {
  return [
    "// Generated by tools/generate-python-docs.mjs.",
    `// Source: ${PYTHON_DOCS_SOURCE_URL}`,
    "// Do not edit; run `npm run generate:python-docs` instead.",
    `export const PYTHON_DOCS_URL = ${JSON.stringify(PYTHON_DOCS_URL)};`,
    "",
    `export const PYTHON_BUILTINS = ${JSON.stringify(entries, null, 2)};`,
    "",
  ].join("\n");
}

async function writeIfChanged(contents) {
  try {
    const existing = await fs.readFile(OUTPUT_PATH, "utf8");
    if (existing === contents) return false;
  } catch {
    // First run: no generated file yet.
  }
  await fs.mkdir(path.dirname(OUTPUT_PATH), { recursive: true });
  await fs.writeFile(OUTPUT_PATH, contents);
  return true;
}

/**
 * Ensure the generated dataset exists and matches the cached docs page.
 * Always reparses (cheap, and it picks up generator changes); only fetches
 * when the cache is missing or `refresh` is set.
 */
export async function generatePythonDocs({ refresh = false } = {}) {
  let html = refresh ? null : await readCachedHtml();
  if (!html) {
    html = await fetchHtml();
    await fs.mkdir(path.dirname(CACHE_PATH), { recursive: true });
    await fs.writeFile(CACHE_PATH, html);
  }

  const entries = parsePythonDocsHtml(html);
  const names = Object.keys(entries);

  if (names.length < MIN_ENTRIES) {
    throw new Error(
      `Parsed only ${names.length} builtins from ${PYTHON_DOCS_SOURCE_URL}; ` +
        "the docs page structure may have changed.",
    );
  }
  const missing = REQUIRED_NAMES.filter((name) => !entries[name]);
  if (missing.length > 0) {
    throw new Error(
      `Missing expected builtins from ${PYTHON_DOCS_SOURCE_URL}: ${missing.join(", ")}`,
    );
  }

  const changed = await writeIfChanged(renderModule(entries));
  return { count: names.length, sourceUrl: PYTHON_DOCS_SOURCE_URL, changed };
}

let pending = null;

/**
 * Memoized entry point for build/export tools. Safe to call from several
 * callers in one process; failures reset the memo so a later run can retry.
 */
export function ensurePythonDocs(options = {}) {
  if (options.refresh) pending = null;
  if (!pending) {
    pending = generatePythonDocs(options).catch((error) => {
      pending = null;
      throw error;
    });
  }
  return pending;
}

async function main() {
  const refresh = process.argv.includes("--refresh");
  const { count, sourceUrl, changed } = await generatePythonDocs({ refresh });
  const state = changed ? "wrote" : "up to date";
  console.log(`Python builtin docs: ${count} entries, ${state} (${sourceUrl})`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch((error) => {
    console.error(error.message);
    process.exitCode = 1;
  });
}
